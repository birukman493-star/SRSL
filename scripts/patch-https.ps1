    server = http.createServer(app);
    console.warn('>>> WARNING: SSL certificates not found in ./certs/ — running on HTTP');
  }

  // Redirect HTTP → HTTPS when running in HTTPS mode
  if (useHttps) {
    const httpPort = port + 1; // e.g. 3004 redirects to 3003
    const httpRedirect = http.createServer((req, res) => {
      res.writeHead(301, { Location: `https://${req.headers.host.replace(httpPort, port)}${req.url}` });
      res.end();
    });
    httpRedirect.listen(httpPort, () =>
      console.log(`>>> HTTP→HTTPS redirect listening on port ${httpPort}`)
    );
  }

  const io = new Server(server, {
'@

